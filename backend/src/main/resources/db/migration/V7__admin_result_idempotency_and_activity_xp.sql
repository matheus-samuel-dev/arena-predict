-- Replay receipts for sensitive administrative commands. The event row lock
-- serializes concurrent retries for the same resource while this unique key
-- prevents a client key from being reused with another payload.
CREATE TABLE arena_admin_operation_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_type VARCHAR(40) NOT NULL,
    idempotency_key VARCHAR(80) NOT NULL,
    resource_id VARCHAR(80) NOT NULL,
    request_fingerprint VARCHAR(200) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_arena_admin_operation_key UNIQUE (operation_type, idempotency_key)
);

CREATE INDEX idx_arena_admin_operation_resource
    ON arena_admin_operation_keys(operation_type, resource_id, created_at);

-- Associate legacy challenge state with the definition window that produced
-- it. Future windows reuse the state row but reset progress/reward safely.
UPDATE arena_user_challenges state
SET window_start = (SELECT definition.starts_at FROM arena_challenge_definitions definition WHERE definition.id = state.challenge_id),
    window_end = (SELECT definition.expires_at FROM arena_challenge_definitions definition WHERE definition.id = state.challenge_id)
WHERE state.window_start IS NULL OR state.window_end IS NULL;

-- The welcome balance is purchasing power for the virtual experience, not
-- participant activity. Preserve every earned reward while removing the
-- initial demo grant (and refunds) from the XP source of truth.
UPDATE arena_point_wallets
SET lifetime_earned = COALESCE((
    SELECT SUM(entry.amount)
    FROM arena_point_transactions entry
    WHERE entry.wallet_id = arena_point_wallets.id
      AND entry.amount > 0
      AND entry.type NOT IN ('REFUND', 'INITIAL_BONUS')
), 0);

