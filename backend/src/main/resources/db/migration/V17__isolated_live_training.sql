CREATE TABLE demo_training_sessions (
    id VARCHAR(36) PRIMARY KEY,
    balance BIGINT NOT NULL CHECK (balance >= 0),
    lifetime_earned BIGINT NOT NULL DEFAULT 0,
    lifetime_used BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_training_session_created ON demo_training_sessions(created_at);
CREATE INDEX ix_training_session_expiry ON demo_training_sessions(expires_at);
CREATE TABLE demo_training_capacity (id INTEGER PRIMARY KEY);
